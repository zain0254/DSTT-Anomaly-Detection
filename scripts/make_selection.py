"""Write configs/datasets.json from results/phase1_eda/file_summary.csv using
the selection confirmed by the owner (REPORT.md section 18: D-21):
  evaluation  = files with >= 1 window touching the test part
  tuning      = real-category files with >= 1 window touching the validation
                part, excluding grok_asg_anomaly (window split across val/test)
  clean_test  = tuning files not in evaluation; their test parts have no
                window and are used for the clean-stream false-alarm rate (D-22)
  model_files = evaluation | tuning (files that need a trained model)
"""
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
EXCLUDE_FROM_TUNING = {"realAWSCloudwatch/grok_asg_anomaly.csv"}

s = pd.read_csv(ROOT / "results" / "phase1_eda" / "file_summary.csv")
evaluation = sorted(s.loc[s.windows_test > 0, "file"])
tuning = sorted(f for f, c, v in zip(s.file, s.category, s.windows_val)
                if v > 0 and c.startswith("real") and f not in EXCLUDE_FROM_TUNING)
clean_test = sorted(set(tuning) - set(evaluation))
by_file = s.set_index("file")
assert all(by_file.loc[f, "windows_test"] == 0 for f in clean_test)
out = {
    "_comment": "Generated by scripts/make_selection.py; see REPORT.md section 18: D-21, D-22.",
    "evaluation": evaluation,
    "tuning": tuning,
    "clean_test": clean_test,
    "model_files": sorted(set(evaluation) | set(tuning)),
}
(ROOT / "configs" / "datasets.json").write_text(json.dumps(out, indent=1) + "\n")
print({k: len(v) for k, v in out.items() if not k.startswith("_")},
      "test windows:", int(by_file.loc[evaluation, "windows_test"].sum()),
      "val windows:", int(by_file.loc[tuning, "windows_val"].sum()))
