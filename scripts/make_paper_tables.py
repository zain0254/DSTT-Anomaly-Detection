"""Generate the paper's LaTeX tables from saved results.

paper/tables/test_summary.tex      from results/phase3/test_summary.csv and selected_params.csv
paper/tables/hypothesis_tests.tex  from results/phase3/hypothesis_tests.csv (P1 vs Base)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from pipeline.methods import METHODS  # noqa: E402

RES = ROOT / "results" / "phase3"
OUT = ROOT / "paper" / "tables"

LABEL = {"Base": "Base \\cite{ahmad2026}", "B1": "B1", "B2": "B2", "S-robust": "S-robust",
         "R2": "R2 EVT \\cite{yu2024evt}", "B3": "B3 RePAD2 \\cite{lee2023repad2}", "B3-k": "B3-k",
         "P1": "P1 (proposed)"}
PNAME = {"p": "p", "k": "k", "lam": "\\lambda", "w": "w"}
# column, header, decimals, higher is better
COLS = [("composite_f1", "Comp.\\ F1", 3, True), ("f1", "Point F1", 3, True), ("precision", "Prec.", 3, True),
        ("event_recall", "Ev.\\ rec.", 3, True), ("fpr", "FPR", 3, False), ("hv_fpr", "HV FPR", 3, False),
        ("corpus_nab_standard", "NAB every", 1, True), ("corpus_nab_standard_first", "NAB first", 1, True),
        ("clean_fpr", "Clean FPR", 3, False), ("clean_false_alarms_per_1000", "Clean FA/1k", 1, False)]


def params_tex(m: str, params: str) -> str:
    p = json.loads(params)
    parts = [f"${PNAME[k]}={v:g}$" for k, v in p.items() if k != "memory"]
    if "memory" in p:
        parts.append(p["memory"])
    return ", ".join(parts) if parts else "--"


def test_summary() -> None:
    s = pd.read_csv(RES / "test_summary.csv").set_index("method").reindex(list(METHODS))
    sel = pd.read_csv(RES / "selected_params.csv").set_index("method")
    lines = ["% Generated by scripts/make_paper_tables.py from results/phase3/test_summary.csv; do not edit.",
             "\\resizebox{\\textwidth}{!}{%",
             "\\begin{tabular}{@{}ll" + "c" * len(COLS) + "@{}}", "\\toprule",
             "Rule & Selected & " + " & ".join(h for _, h, _, _ in COLS) + " \\\\", "\\midrule"]
    best = {}
    for c, _, d, hi in COLS:
        r = s[f"{c}_mean"].round(d)
        best[c] = r.max() if hi else r.min()
    for m in METHODS:
        cells = []
        for c, _, d, hi in COLS:
            mean, sd = s.loc[m, f"{c}_mean"], s.loc[m, f"{c}_sd"]
            if round(mean, d) == best[c]:
                cells.append(f"$\\mathbf{{{mean:.{d}f}}} \\pm \\mathbf{{{sd:.{d}f}}}$")
            else:
                cells.append(f"${mean:.{d}f} \\pm {sd:.{d}f}$")
        lines.append(f"{LABEL[m]} & {params_tex(m, sel.loc[m, 'params'])} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}}"]
    (OUT / "test_summary.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def hypothesis_tests() -> None:
    h = pd.read_csv(RES / "hypothesis_tests.csv")
    h = h[h.comparison == "primary"]
    names = {"composite_f1": "Composite F1", "hv_fpr": "HV FPR", "clean_fpr": "Clean FPR",
             "clean_false_alarms_per_1000": "Clean FA/1k", "nab_standard": "NAB every-step"}
    dec = {"composite_f1": 3, "hv_fpr": 3, "clean_fpr": 4, "clean_false_alarms_per_1000": 1, "nab_standard": 1}
    lines = ["% Generated by scripts/make_paper_tables.py from results/phase3/hypothesis_tests.csv; do not edit.",
             "\\footnotesize", "\\setlength{\\tabcolsep}{3pt}",
             "\\begin{tabular}{@{}lrrcrr@{}}", "\\toprule",
             "Metric & $n$ & Diff. & 95\\% CI & W/L & $p$ \\\\", "\\midrule"]
    for r in h.itertuples():
        d = dec[r.metric]
        lines.append(f"{names[r.metric]} & {r.n_files} & ${r.mean_diff:.{d}f}$ & "
                     f"$[{r.ci95_low:.{d}f}, {r.ci95_high:.{d}f}]$ & {r.wins}/{r.losses} & {r.p:.3f} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (OUT / "hypothesis_tests.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    test_summary()
    hypothesis_tests()
    print((OUT / "test_summary.tex").read_text(encoding="utf-8"))
    print((OUT / "hypothesis_tests.tex").read_text(encoding="utf-8"))
