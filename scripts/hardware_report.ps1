# Write results/environment/hardware.md (Windows) and print it.
# Usage: powershell -ExecutionPolicy Bypass -File scripts/hardware_report.ps1
$root = Split-Path -Parent $PSScriptRoot
$os  = Get-CimInstance Win32_OperatingSystem
$cpu = Get-CimInstance Win32_Processor
$cs  = Get-CimInstance Win32_ComputerSystem
$disk = Get-PSDrive ($root.Substring(0,1))

$lines = @()
$lines += "# Hardware"
$lines += ""
$lines += "Generated by scripts/hardware_report.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm')."
$lines += ""
$lines += "| Item | Value |"
$lines += "|---|---|"
$lines += "| OS | $($os.Caption), version $($os.Version), build $($os.BuildNumber) |"
$lines += "| CPU | $($cpu.Name.Trim()) |"
$lines += "| Cores / threads | $($cpu.NumberOfCores) / $($cpu.NumberOfLogicalProcessors) |"
$lines += "| RAM total | $([math]::Round($cs.TotalPhysicalMemory/1GB,1)) GB |"
$lines += "| RAM free at report time | $([math]::Round($os.FreePhysicalMemory/1MB,1)) GB |"

$smi = Get-Command nvidia-smi -ErrorAction SilentlyContinue
if ($smi) {
    $g = (& nvidia-smi --query-gpu=name,memory.total,driver_version --format=csv,noheader) -split "`n"
    foreach ($row in $g) { if ($row.Trim()) { $lines += "| GPU (nvidia-smi) | $($row.Trim()) |" } }
}
Get-CimInstance Win32_VideoController | Where-Object { $_.Name -notmatch 'NVIDIA' } | ForEach-Object {
    $lines += "| GPU (other) | $($_.Name) |"
}

$pys = @()
foreach ($v in @('3.14','3.13','3.12','3.11','3.10')) {
    $out = & py "-$v" --version 2>$null
    if ($LASTEXITCODE -eq 0 -and $out) { $pys += $out.Trim() }
}
$lines += "| Python installs (py launcher) | $($pys -join ', ') |"
$venv = Join-Path $root "envs\pipeline\Scripts\python.exe"
if (Test-Path $venv) {
    $vp = & $venv --version
    $tv = & $venv -c "import torch; print(torch.__version__, 'CUDA' if torch.cuda.is_available() else 'CPU-only')"
    $lines += "| Pipeline venv | $vp, torch $tv |"
}
$lines += "| Free disk on $($disk.Name): | $([math]::Round($disk.Free/1GB,1)) GB of $([math]::Round(($disk.Free+$disk.Used)/1GB,1)) GB |"
$lines += ""
$lines += "Notes"
$lines += ""
$lines += "- The pipeline uses the CPU build of PyTorch; the GPU is not used."
$lines += "- Free RAM varies with other programs; close them before long runs."

$text = $lines -join "`n"
$utf8 = New-Object System.Text.UTF8Encoding($false)
New-Item -ItemType Directory -Force -Path (Join-Path $root "results\environment") | Out-Null
[System.IO.File]::WriteAllText((Join-Path $root "results\environment\hardware.md"), $text + "`n", $utf8)
Write-Output $text
